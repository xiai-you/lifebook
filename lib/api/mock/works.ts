interface WorkInput {
  title: string;
  summary: string;
  categoryL1: string;
  categoryL2: string;
  authorId: string;
  tags: string[];
  emotion?: string;
  city?: string;
  country?: string;
  viewCount: number;
  likeCount: number;
  commentCount: number;
  readMinutes: number;
  coverRatio: CoverRatio;
  coverColor: string;
  publishAt: string;
  subtitle?: string;
  feedKind?: FeedKind;
  momentLabel?: string;
  featuredLine?: string;
}

const FEED_KINDS: FeedKind[] = ["photo", "essay", "novel"];

function makeWork(input: WorkInput): Work {
  seq += 1;
  const id = `work-${seq}`;
  return {
    id,
    authorId: input.authorId,
    author: authors[input.authorId],
    title: input.title,
    subtitle: input.subtitle ?? null,
    summary: input.summary,
    coverImage: photoFor({
      id,
      categoryL1: input.categoryL1,
      emotion: input.emotion ?? null,
      tags: input.tags,
    }),
    coverColor: input.coverColor,
    feedKind: input.feedKind ?? FEED_KINDS[seq % 3],
    momentLabel: input.momentLabel ?? null,
    featuredLine: input.featuredLine ?? null,
    categoryL1: input.categoryL1,
    categoryL2: input.categoryL2,
    categoryL3: null,
    tags: input.tags,
    emotion: input.emotion ?? null,
    city: input.city ?? null,
    country: input.country ?? "中国",
    totalWords: 6000 + seq * 173,
    chapterCount: 6 + (seq % 9),
    status: seq % 3 === 0 ? "completed" : "ongoing",
    visibility: "public",
    viewCount: input.viewCount,
    likeCount: input.likeCount,
    collectCount: Math.round(input.likeCount * 0.42),
    commentCount: input.commentCount,
    resonateCount: Math.round(input.likeCount * 0.28),
    readMinutes: input.readMinutes,
    coverRatio: input.coverRatio,
    publishAt: input.publishAt,
    createdAt: input.publishAt,
    updatedAt: input.publishAt,
  };
}

